CREATE TABLE `site_audit_pages` (
  `id` varchar(191) NOT NULL,
  `url` varchar(1000) NOT NULL,
  `sourceSitemap` varchar(191) DEFAULT NULL,
  `httpStatus` int DEFAULT NULL,
  `redirectTo` varchar(1000) DEFAULT NULL,
  `crawlError` varchar(191) DEFAULT NULL,
  `lastCrawledAt` datetime(3) DEFAULT NULL,
  `isIndexed` tinyint(1) DEFAULT NULL,
  `indexingVerdict` varchar(191) DEFAULT NULL,
  `indexingIssues` text DEFAULT NULL,
  `lastInspectedAt` datetime(3) DEFAULT NULL,
  `lcpMs` int DEFAULT NULL,
  `cls` double DEFAULT NULL,
  `inpMs` int DEFAULT NULL,
  `performanceScore` int DEFAULT NULL,
  `lastVitalsCheckAt` datetime(3) DEFAULT NULL,
  `createdAt` datetime(3) NOT NULL DEFAULT current_timestamp(3),
  `updatedAt` datetime(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `site_audit_pages_url_key` (`url`(768)),
  KEY `site_audit_pages_httpStatus_idx` (`httpStatus`),
  KEY `site_audit_pages_isIndexed_idx` (`isIndexed`),
  KEY `site_audit_pages_lastCrawledAt_idx` (`lastCrawledAt`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
